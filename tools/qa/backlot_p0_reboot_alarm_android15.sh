#!/usr/bin/env bash
# P0 disposable Android 15 emulator only. NO owner devices or live data.
# A real emulator reboot occurs between two separate instrumentation processes.
set -euo pipefail
out=output/p0-reboot-alarm
mkdir -p "$out"
adb wait-for-device
adb shell getprop sys.boot_completed | grep -qx '1'
adb install -r app/build/outputs/apk/debug/app-debug.apk
adb install -r app/build/outputs/apk/androidTest/debug/app-debug-androidTest.apk
adb shell am force-stop com.framebynavin.app || true
adb shell pm clear com.framebynavin.app > "$out/CLEARED_CI_EMULATOR_ONLY.txt"
adb shell pm grant com.framebynavin.app android.permission.POST_NOTIFICATIONS
adb shell appops set com.framebynavin.app SCHEDULE_EXACT_ALARM allow
adb shell appops get com.framebynavin.app SCHEDULE_EXACT_ALARM > "$out/EXACT_ALARM_APPOP.txt"

# PREPARE writes exactly one synthetic challenge and installs its next OS alarm.
timeout --signal=TERM --kill-after=15s 5m adb shell am instrument -w -r \
  -e hardeningTestEnvironment ci-emulator \
  -e class com.framebynavin.app.personal.P0RebootChallengeAlarmDeviceTest#writeAndArmSyntheticAlarmBeforeRealReboot \
  com.framebynavin.app.test/androidx.test.runner.AndroidJUnitRunner \
  > "$out/BEFORE_REBOOT_TEST.txt" 2>&1 || { cat "$out/BEFORE_REBOOT_TEST.txt"; exit 1; }
cat "$out/BEFORE_REBOOT_TEST.txt"
grep -q 'OK (1 test)' "$out/BEFORE_REBOOT_TEST.txt"
due=$(sed -n 's/.*P0_REBOOT_DUE_EPOCH_MS=\([0-9][0-9]*\).*/\1/p' "$out/BEFORE_REBOOT_TEST.txt" | tail -1)
test -n "$due"
printf '%s\n' "$due" > "$out/DUE_EPOCH_MS.txt"
previous_boot=$(adb shell cat /proc/sys/kernel/random/boot_id | tr -d '\r')
test -n "$previous_boot"
echo "REAL_REBOOT_START_UTC=$(date -u +%Y-%m-%dT%H:%M:%SZ)" > "$out/REBOOT_PROOF.txt"
# No app launches, simulated BOOT_COMPLETED, or simulated HABIT_FIRE broadcasts.
adb reboot
sleep 8
timeout --signal=TERM --kill-after=15s 8m bash -c '
  while :; do
    if adb wait-for-device >/dev/null 2>&1 &&
      test "$(adb shell getprop sys.boot_completed 2>/dev/null | tr -d "\r")" = "1"; then
      break
    fi
    sleep 3
  done
'
current_boot=$(adb shell cat /proc/sys/kernel/random/boot_id | tr -d '\r')
test -n "$current_boot"
test "$current_boot" != "$previous_boot" || {
  echo "Device did not actually reboot" >&2; exit 1;
}
echo "ACTUAL_BOOT_ID_CHANGED=yes" >> "$out/REBOOT_PROOF.txt"
echo "REAL_REBOOT_COMPLETE_UTC=$(date -u +%Y-%m-%dT%H:%M:%SZ)" >> "$out/REBOOT_PROOF.txt"
# Allow credential-encrypted DataStore access after reboot; do not launch app.
adb shell input keyevent 82 || true

# Do NOT inspect by launching Backlot before the scheduled due time; the
# system BOOT_COMPLETED receiver alone must re-arm the OS alarm.
deadline=$((due + 180000))
while :; do
  now=$(date -u +%s%3N)
  if (( now >= due + 40000 )); then break; fi
  if (( now > deadline )); then echo "Timed out awaiting post-due inspection" >&2; exit 1; fi
  sleep 3
done
printf '%s\n' "VERIFIER_START_EPOCH_MS=$(date -u +%s%3N)" >> "$out/REBOOT_PROOF.txt"

# Separate instrumentation process starts AFTER the due time. Evidence must
# have been generated by Android's reboot recovery and AlarmManager beforehand.
timeout --signal=TERM --kill-after=15s 5m adb shell am instrument -w -r \
  -e hardeningTestEnvironment ci-emulator \
  -e class com.framebynavin.app.personal.P0RebootChallengeAlarmDeviceTest#verifyOsFiredAfterActualRebootWithoutOpeningApp \
  com.framebynavin.app.test/androidx.test.runner.AndroidJUnitRunner \
  > "$out/AFTER_REBOOT_TEST.txt" 2>&1 || { cat "$out/AFTER_REBOOT_TEST.txt"; exit 1; }
cat "$out/AFTER_REBOOT_TEST.txt"
grep -q 'OK (1 test)' "$out/AFTER_REBOOT_TEST.txt"
echo 'PASS: synthetic challenge persisted, actual emulator reboot, BOOT_COMPLETED OS recovery, naturally timed alarm and notification posted without opening app' > "$out/RESULT.txt"
echo 'Limits: Android 15 awake CI emulator only; no physical OEM, Doze, force-stop guarantees, audible quality, or production release.' > "$out/LIMITS.txt"
